using System;
using System.IO;
using Aspose.Diagram;

class Program
{
    static void Main(string[] args)
    {
        // Expect the first argument to be the path of the Visio file containing VBA macros.
        if (args.Length == 0)
        {
            Console.Error.WriteLine("Error: No input file path provided.");
            return;
        }

        string inputPath = args[0];

        // Guard: ensure the input file exists.
        if (!File.Exists(inputPath))
        {
            Console.Error.WriteLine($"Error: File not found - {inputPath}");
            return;
        }

        try
        {
            // Load the diagram from the specified file.
            Diagram diagram = new Diagram(inputPath);

            // Verify that the diagram contains a VBA project.
            if (diagram.VbaProject == null)
            {
                Console.Error.WriteLine("Warning: The loaded diagram does not contain a VBA project.");
            }
            else
            {
                Console.WriteLine($"VBA Project Name: {diagram.VbaProject.Name}");
                Console.WriteLine($"Is Signed: {diagram.VbaProject.IsSigned}");
                Console.WriteLine($"Modules count: {diagram.VbaProject.Modules.Count}");
            }

            // Prepare a memory stream for network transmission.
            using (MemoryStream memoryStream = new MemoryStream())
            {
                // Save the diagram, preserving VBA macros, directly into the memory stream.
                // Use the macro-enabled format Vsdm.
                diagram.Save(memoryStream, SaveFileFormat.Vsdm);

                // Reset the stream position to the beginning before reading.
                memoryStream.Position = 0;

                // Example: obtain the byte array (could be sent over network).
                byte[] diagramBytes = memoryStream.ToArray();

                // Output the size of the generated byte array.
                Console.WriteLine($"Diagram saved to memory stream. Byte size: {diagramBytes.Length}");
                // At this point, diagramBytes can be transmitted over the network.
            }

            // Dispose the diagram to free resources.
            diagram.Dispose();
        }
        catch (Exception ex)
        {
            // Write any Aspose or I/O errors to the error console.
            Console.Error.WriteLine($"An error occurred: {ex.Message}");
        }
    }
}